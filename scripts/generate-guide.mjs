// Generates src/guide-texts.ts from the skill, so that the server and the command hand out the same
// texts to an agent that has no skill installed. With --check it only compares.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join } from "node:path";

const root = fileURLToPath(new URL("..", import.meta.url));
const skill = join(root, "skills/wtctl");
const target = join(root, "src/guide-texts.ts");
const read = (path) => readFileSync(join(skill, path), "utf8").replaceAll("\r\n", "\n");
function replaceOnce(text, from, to) {
  if (text.split(from).length !== 2)
    throw new Error(`Expected exactly one occurrence in SKILL.md: ${from}`);
  return text.replace(from, to);
}

const source = read("SKILL.md");
const end = source.indexOf("\n---\n", 4);
if (!source.startsWith("---\n") || end < 0) throw new Error("SKILL.md has no front matter.");
let start = source.slice(end + 5).trim();

// The table of references in SKILL.md gives the topics, their order and their titles.
const topics = [
  ...start.matchAll(/^\| (.+?) \| \[references\/([\w-]+)\.md\]\(references\/\2\.md\) \|$/gm),
].map(([, title, topic]) => ({ topic, title }));
const files = readdirSync(join(skill, "references"))
  .filter((name) => name.endsWith(".md"))
  .map((name) => name.slice(0, -3));
for (const name of files)
  if (!topics.some((item) => item.topic === name))
    throw new Error(`references/${name}.md is missing from the table in SKILL.md.`);
if (topics.length !== files.length) throw new Error("The table in SKILL.md names a missing file.");

start = replaceOnce(
  start,
  "Читай нужный файл, когда дошёл до такой задачи.",
  'Открой нужную тему, когда дошёл до такой задачи: `hcm_guide {topic:"queries"}`, из командной строки — `wtctl guide queries`.',
);
start = replaceOnce(start, "| Задача | Файл |", "| Задача | Тема |");
start = start.replace(/\[references\/([\w-]+)\.md\]\(references\/\1\.md\)/g, "`$1`");

const pages = [
  { topic: "start", title: "Порядок работы и главные правила", text: start },
  ...topics.map(({ topic, title }) => ({
    topic,
    title,
    text: read(`references/${topic}.md`)
      .trim()
      .replace(/см\. \[([\w-]+)\.md\]\(\1\.md\)/g, "см. тему `$1`"),
  })),
];
for (const page of pages)
  if (/\]\([^)]*\.md[)#]/.test(page.text))
    throw new Error(
      `A link to a file is left in the topic ${page.topic}; write it as "см. [name.md](name.md)".`,
    );

const generated = [
  "// Generated by scripts/generate-guide.mjs from skills/wtctl. Do not edit: run npm run generate.",
  "export interface GuidePage {",
  "  readonly topic: string;",
  "  readonly title: string;",
  "  readonly text: string;",
  "}",
  "export const GUIDE_PAGES: readonly GuidePage[] = [",
  ...pages.map(
    (page) =>
      `  { topic: ${JSON.stringify(page.topic)}, title: ${JSON.stringify(page.title)}, text: ${JSON.stringify(page.text)} },`,
  ),
  "];",
  "",
].join("\n");

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8").replaceAll("\r\n", "\n");
  } catch {}
  if (current !== generated) {
    console.error("src/guide-texts.ts does not match the skill: run npm run generate.");
    process.exit(1);
  }
  console.log(`Guide texts match the skill: ${pages.length} topics.`);
} else {
  writeFileSync(target, generated);
  console.log(
    `src/guide-texts.ts: ${pages.length} topics, ${Math.round(generated.length / 1024)} KB.`,
  );
}
